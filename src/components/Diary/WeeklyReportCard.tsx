// ============================================================
// src/components/Diary/WeeklyReportCard.tsx
// Weekly Clinical Summary & Downloadable/Printable Report Card
// WCAG AA compliant layout with print formatting and text download
// ============================================================

import { memo, useCallback } from 'react';
import type { WeeklyHealthSummary, HealthDiaryEntry } from '@/types/diary';

interface WeeklyReportCardProps {
  summary: WeeklyHealthSummary;
  entries: HealthDiaryEntry[];
  zoneName: string;
}

export const WeeklyReportCard = memo(function WeeklyReportCard({
  summary,
  entries,
  zoneName,
}: WeeklyReportCardProps) {
  const handlePrint = useCallback(() => {
    window.print();
  }, []);

  const handleDownload = useCallback(() => {
    const lines = [
      '============================================================',
      '           BREATHEBRIDGE WEEKLY HEALTH & SMOG REPORT        ',
      '============================================================',
      `Zone:                 ${zoneName}`,
      `Period:               ${summary.startDate} to ${summary.endDate}`,
      `Logged Days:          ${summary.totalEntries} days`,
      `Average Ambient AQI:  ${summary.averageAqi}`,
      '------------------------------------------------------------',
      'AVERAGE SYMPTOM SCORES (0 to 3 scale):',
      `  • Cough / Throat:        ${summary.averageCough} / 3`,
      `  • Eye Irritation:        ${summary.averageEyeIrritation} / 3`,
      `  • Breathlessness:        ${summary.averageBreathlessness} / 3`,
      `  • Aggregate Symptom Load:${summary.averageTotalSymptomScore} / 9`,
      '------------------------------------------------------------',
      `Peak Distress Day:    ${summary.peakSymptomDay ? `${summary.peakSymptomDay.date} (Score: ${summary.peakSymptomDay.score}/9, AQI: ${summary.peakSymptomDay.aqi})` : 'None'}`,
      '------------------------------------------------------------',
      'CLINICAL ADVISORY:',
      `  ${summary.clinicalAdvisory}`,
      '============================================================',
      'RECENT DAILY ENTRIES:',
      ...entries.slice(-7).map(
        (e) =>
          `[${e.date}] AQI: ${e.aqi.toString().padEnd(3)} | Cough: ${e.cough} | Eyes: ${e.eyeIrritation} | Breath: ${e.breathlessness} | Notes: ${e.notes || 'None'}`
      ),
      '============================================================',
      'Generated by BreatheBridge · WCAG 2.2 Level AA Standard',
    ];

    if (typeof URL !== 'undefined' && typeof URL.createObjectURL === 'function') {
      const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `breathebridge-health-report-${summary.endDate}.txt`;
      a.addEventListener('click', (e) => {
        // Suppress navigation warnings in headless/JSDOM environments
        if (typeof window !== 'undefined' && !window.location.protocol.startsWith('http')) {
          e.preventDefault();
        }
      });
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      if (typeof URL.revokeObjectURL === 'function') {
        URL.revokeObjectURL(url);
      }
    }
  }, [summary, entries, zoneName]);

  return (
    <div
      id="weekly-health-report"
      className="bg-slate-900/60 rounded-3xl border border-slate-700/50 p-6 flex flex-col gap-5 backdrop-blur-md"
    >
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-800 pb-4">
        <div>
          <span className="text-xs uppercase font-bold tracking-wider text-indigo-400">
            Physician-Ready Summary
          </span>
          <h3 className="text-lg font-black text-white mt-0.5 flex items-center gap-2">
            <span aria-hidden="true">📋</span> Weekly Health &amp; Exposure Report
          </h3>
          <p className="text-xs text-slate-400 mt-0.5">
            {summary.startDate} to {summary.endDate} · {summary.totalEntries} logged days in {zoneName}
          </p>
        </div>

        {/* Download & Print Actions */}
        <div className="flex items-center gap-2 print:hidden">
          <button
            type="button"
            onClick={handleDownload}
            aria-label="Download weekly report as text file"
            className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-bold bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 transition-all focus:outline-none focus:ring-2 focus:ring-indigo-500"
          >
            <span aria-hidden="true">💾</span> Download Report
          </button>
          <button
            type="button"
            onClick={handlePrint}
            aria-label="Print weekly health summary"
            className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-bold bg-indigo-600 hover:bg-indigo-500 text-white shadow-lg shadow-indigo-950/50 transition-all focus:outline-none focus:ring-2 focus:ring-indigo-400"
          >
            <span aria-hidden="true">🖨️</span> Print Summary
          </button>
        </div>
      </div>

      {/* KPI Highlights */}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
        <div className="bg-slate-800/40 border border-slate-700/50 rounded-2xl p-4 flex flex-col justify-between">
          <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
            7-Day Avg AQI
          </span>
          <div className="text-2xl font-black text-sky-400 mt-1">
            {summary.averageAqi}
          </div>
          <span className="text-[11px] text-slate-400 mt-1">Ambient air exposure</span>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-2xl p-4 flex flex-col justify-between">
          <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
            Avg Cough Score
          </span>
          <div className="text-2xl font-black text-amber-400 mt-1">
            {summary.averageCough} <span className="text-xs font-normal text-slate-400">/ 3</span>
          </div>
          <span className="text-[11px] text-slate-400 mt-1">Throat &amp; bronchial</span>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-2xl p-4 flex flex-col justify-between">
          <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
            Avg Eye Irritation
          </span>
          <div className="text-2xl font-black text-rose-400 mt-1">
            {summary.averageEyeIrritation} <span className="text-xs font-normal text-slate-400">/ 3</span>
          </div>
          <span className="text-[11px] text-slate-400 mt-1">Ocular stinging load</span>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-2xl p-4 flex flex-col justify-between">
          <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
            Avg Breathlessness
          </span>
          <div className="text-2xl font-black text-purple-400 mt-1">
            {summary.averageBreathlessness} <span className="text-xs font-normal text-slate-400">/ 3</span>
          </div>
          <span className="text-[11px] text-slate-400 mt-1">Chest constriction</span>
        </div>
      </div>

      {/* Clinical Advisory & Peak Warning */}
      <div className="bg-indigo-950/30 border border-indigo-500/40 rounded-2xl p-4 flex flex-col gap-2">
        <div className="flex items-center gap-2">
          <span className="text-base" aria-hidden="true">🩺</span>
          <h4 className="text-xs font-bold text-indigo-300 uppercase tracking-wider">
            Physician &amp; Lifestyle Advisory
          </h4>
        </div>
        <p className="text-xs text-slate-200 leading-relaxed">
          {summary.clinicalAdvisory}
        </p>
        {summary.peakSymptomDay && (
          <p className="text-[11px] text-amber-300 font-medium">
            ⚠️ Peak symptom spike logged on <strong>{summary.peakSymptomDay.date}</strong> (Score: {summary.peakSymptomDay.score}/9) coinciding with an AQI of {summary.peakSymptomDay.aqi}.
          </p>
        )}
      </div>

      {/* Print-only footer */}
      <div className="hidden print:block text-[10px] text-gray-500 border-t pt-2 mt-2">
        Report generated from BreatheBridge Health Diary · User records stored per-user in compliance with security &amp; privacy policies.
      </div>
    </div>
  );
});
